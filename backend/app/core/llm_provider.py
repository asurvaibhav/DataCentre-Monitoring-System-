"""
AO-02 Unified LLM Provider Abstraction.

Supports Google Gemini API and OpenAI API via structured Pydantic outputs.
Falls back to a deterministic mock provider when no API key is configured, so
the pipeline runs end-to-end in sandbox/demo environments without external
credentials. All providers return Pydantic model instances.
"""

from __future__ import annotations

import json
import os
from abc import ABC, abstractmethod
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, Optional, Type

from dotenv import load_dotenv

load_dotenv(dotenv_path=Path(__file__).resolve().parent.parent.parent / ".env", override=True)

from pydantic import BaseModel


class LLMProvider(ABC):
    """Abstract provider for structured LLM generation."""

    @abstractmethod
    async def generate_structured(
        self,
        prompt: str,
        schema: Type[BaseModel],
        system_prompt: Optional[str] = None,
        temperature: float = 0.2,
    ) -> BaseModel:
        """Generate a structured Pydantic model instance from a prompt."""
        ...


class _MockProvider(LLMProvider):
    """Deterministic fallback that produces plausible structured outputs
    without calling any external LLM API. Used when no provider key is set."""

    async def generate_structured(
        self,
        prompt: str,
        schema: Type[BaseModel],
        system_prompt: Optional[str] = None,
        temperature: float = 0.2,
    ) -> BaseModel:
        # Build a heuristic instance based on schema name + prompt keywords.
        return _heuristic_instance(schema, prompt)


def _heuristic_instance(schema: Type[BaseModel], prompt: str) -> BaseModel:
    fields = schema.model_fields
    data: Dict[str, Any] = {}

    lower = prompt.lower()

    for field_name, field_info in fields.items():
        fn = field_name.lower()
        field_type = field_info.annotation

        # Handle Optional / Union types by peeking at the inner type.
        origin = getattr(field_type, "__origin__", None)
        args = getattr(field_type, "__args__", None)

        if fn == "root_cause_summary":
            data[field_name] = "Heuristic RCA: sustained utilization growth coupled with " \
                "cross-resource correlation indicates workload-driven saturation."
        elif fn == "attributed_tenant_id":
            data[field_name] = "T1" if "t1" in lower else "T2"
        elif fn == "driving_workload_signature":
            data[field_name] = "Batch analytics workload on tenant DB cluster"
        elif fn == "correlated_signals":
            data[field_name] = ["Rack thermal rise", "Storage IOPS increase"]
        elif fn == "confidence_score":
            data[field_name] = 0.78
        elif fn == "investigation_notes":
            data[field_name] = "Mock investigation notes generated by fallback provider."
        elif fn == "title":
            data[field_name] = "Capacity rebalancing recommendation"
        elif fn == "recommended_action":
            data[field_name] = ("Rebalance affected tenant workloads to under-utilized "
                                "racks to extend lead time.")
        elif fn == "simulated_post_action_utilization_pct":
            data[field_name] = 70.0
        elif fn == "projected_lead_time_extension_weeks":
            data[field_name] = 4.0
        elif fn == "mutates_live_facility_controls":
            data[field_name] = False
        elif fn == "risk_score":
            data[field_name] = 0.55
        elif fn == "blast_radius_summary":
            data[field_name] = "Single rack; limited to one tenant workload."
        elif fn == "sla_impact_assessment":
            data[field_name] = "Moderate; predicted exhaustion within 4-8 weeks."
        elif fn == "gate_decision":
            data[field_name] = "REQUIRE_HUMAN_APPROVAL"
        elif fn == "selected_option_id":
            data[field_name] = "rem-000000"
        elif fn == "option_id":
            import uuid
            data[field_name] = f"rem-{uuid.uuid4().hex[:6]}"
        elif field_type is str:
            data[field_name] = f"mock-{field_name}"
        elif field_type is int:
            data[field_name] = 1
        elif field_type is float:
            data[field_name] = 0.5
        elif field_type is bool:
            data[field_name] = False
        elif field_type is datetime:
            data[field_name] = datetime.now(timezone.utc)
        elif origin is list and args:
            item_type = args[0]
            if item_type is str:
                data[field_name] = []
            else:
                data[field_name] = []
        elif origin is dict:
            data[field_name] = {}
        elif field_type is tuple:
            data[field_name] = (0.0, 0.0)
        else:
            # Use Pydantic default if available.
            if field_info.default is not None:
                data[field_name] = field_info.default
            elif field_info.default_factory is not None:
                data[field_name] = field_info.default_factory()
            else:
                data[field_name] = None

    try:
        return schema(**data)
    except Exception:
        # Last resort: instantiate with defaults only.
        defaults: Dict[str, Any] = {}
        for fname, finfo in fields.items():
            if finfo.default is not None:
                defaults[fname] = finfo.default
            elif finfo.default_factory is not None:
                defaults[fname] = finfo.default_factory()
        return schema(**defaults)


class GeminiProvider(LLMProvider):
    """Google Gemini API provider with structured JSON output."""

    def __init__(self, api_key: str, model_name: str = "gemini-3.5-flash") -> None:
        try:
            from google import genai
            from google.genai import types
        except ImportError as exc:  # pragma: no cover - dependency missing
            raise ImportError(
                "google-genai is required for the Gemini provider. "
                "Install it with `pip install google-genai`."
            ) from exc

        self._types = types
        self._model_name = model_name
        self._client = genai.Client(
            api_key=api_key,
            http_options=types.HttpOptions(
                timeout=120_000,
                retry_options=types.HttpRetryOptions(
                    attempts=5,
                    initial_delay=2.0,
                    max_delay=20.0,
                    exp_base=2.0,
                    jitter=1.0,
                    http_status_codes=[429, 500, 502, 503, 504],
                ),
            ),
        )

    @staticmethod
    def _parse_response(response: Any, schema: Type[BaseModel]) -> BaseModel:
        parsed = getattr(response, "parsed", None)
        if isinstance(parsed, schema):
            return parsed
        if isinstance(parsed, dict):
            return schema(**parsed)
        if parsed is not None:
            return schema.model_validate(parsed)

        text = (getattr(response, "text", None) or "{}").strip()
        if text.startswith("```"):
            lines = text.splitlines()
            if lines and lines[0].startswith("```"):
                lines = lines[1:]
            if lines and lines[-1].strip() == "```":
                lines = lines[:-1]
            text = "\n".join(lines).strip()
        return schema(**json.loads(text))

    async def generate_structured(
        self,
        prompt: str,
        schema: Type[BaseModel],
        system_prompt: Optional[str] = None,
        temperature: float = 0.2,
    ) -> BaseModel:
        schema_json = schema.model_json_schema()
        full_prompt = prompt
        if system_prompt:
            full_prompt = f"{system_prompt}\n\n{prompt}"
        full_prompt += (
            "\n\nReturn ONLY a valid JSON object that conforms to this schema:\n"
            f"{json.dumps(schema_json, indent=2)}"
        )

        config = self._types.GenerateContentConfig(
            response_mime_type="application/json",
            response_schema=schema,
            system_instruction=system_prompt,
            temperature=temperature,
        )
        response = await self._client.aio.models.generate_content(
            model=self._model_name,
            contents=full_prompt,
            config=config,
        )
        return self._parse_response(response, schema)


class OpenAIProvider(LLMProvider):
    """OpenAI API provider with structured JSON output."""

    def __init__(self, api_key: str, model_name: str = "gpt-4o-mini") -> None:
        try:
            from openai import AsyncOpenAI
        except ImportError as exc:  # pragma: no cover - dependency missing
            raise ImportError(
                "openai is required for the OpenAI provider. "
                "Install it with `pip install openai`."
            ) from exc
        self._client = AsyncOpenAI(api_key=api_key)
        self._model_name = model_name

    async def generate_structured(
        self,
        prompt: str,
        schema: Type[BaseModel],
        system_prompt: Optional[str] = None,
        temperature: float = 0.2,
    ) -> BaseModel:
        schema_json = schema.model_json_schema()
        messages: list[Dict[str, str]] = []
        if system_prompt:
            messages.append({"role": "system", "content": system_prompt})
        messages.append(
            {
                "role": "user",
                "content": (
                    f"{prompt}\n\nReturn ONLY a valid JSON object conforming to "
                    f"this schema: {json.dumps(schema_json)}"
                ),
            }
        )
        response = await self._client.chat.completions.create(
            model=self._model_name,
            messages=messages,
            temperature=temperature,
            response_format={"type": "json_object"},
        )
        text = (response.choices[0].message.content or "{}").strip()
        if text.startswith("```"):
            lines = text.splitlines()
            if lines and lines[0].startswith("```"):
                lines = lines[1:]
            if lines and lines[-1].strip() == "```":
                lines = lines[:-1]
            text = "\n".join(lines).strip()
        data = json.loads(text)
        return schema(**data)


class FallbackProvider(LLMProvider):
    """Wraps a primary LLM provider and falls back to a secondary provider or mock
    if the primary throws an exception (e.g. 503 high demand, 429 quota, etc.)."""

    def __init__(self, primary: LLMProvider, secondary: LLMProvider) -> None:
        self.primary = primary
        self.secondary = secondary

    async def generate_structured(
        self,
        prompt: str,
        schema: Type[BaseModel],
        system_prompt: Optional[str] = None,
        temperature: float = 0.2,
    ) -> BaseModel:
        try:
            return await self.primary.generate_structured(prompt, schema, system_prompt, temperature)
        except Exception as exc:
            import logging
            logging.warning("Primary LLM provider failed (%s); falling back to secondary provider.", exc)
            return await self.secondary.generate_structured(prompt, schema, system_prompt, temperature)


def get_llm_provider() -> LLMProvider:
    """Factory: return a configured LLM provider with graceful fallback or the deterministic mock."""
    provider_name = os.getenv("LLM_PROVIDER", "auto").lower()
    openai_key = os.getenv("OPENAI_API_KEY")
    gemini_key = os.getenv("GEMINI_API_KEY")
    mock = _MockProvider()

    if provider_name == "mock":
        return mock

    primary: Optional[LLMProvider] = None
    secondary: Optional[LLMProvider] = None

    if provider_name == "openai":
        if openai_key:
            model_name = os.getenv("OPENAI_MODEL", "gpt-4o-mini")
            primary = OpenAIProvider(openai_key, model_name)
            if gemini_key:
                secondary = GeminiProvider(gemini_key, os.getenv("GEMINI_MODEL", "gemini-3.5-flash"))
        elif gemini_key:
            primary = GeminiProvider(gemini_key, os.getenv("GEMINI_MODEL", "gemini-3.5-flash"))
        else:
            return mock
    elif provider_name == "gemini":
        if gemini_key:
            model_name = os.getenv("GEMINI_MODEL", "gemini-3.5-flash")
            primary = GeminiProvider(gemini_key, model_name)
            if openai_key:
                secondary = OpenAIProvider(openai_key, os.getenv("OPENAI_MODEL", "gpt-4o-mini"))
        elif openai_key:
            primary = OpenAIProvider(openai_key, os.getenv("OPENAI_MODEL", "gpt-4o-mini"))
        else:
            return mock
    else:  # auto
        if openai_key:
            primary = OpenAIProvider(openai_key, os.getenv("OPENAI_MODEL", "gpt-4o-mini"))
            if gemini_key:
                secondary = GeminiProvider(gemini_key, os.getenv("GEMINI_MODEL", "gemini-3.5-flash"))
        elif gemini_key:
            primary = GeminiProvider(gemini_key, os.getenv("GEMINI_MODEL", "gemini-3.5-flash"))
        else:
            return mock

    if primary:
        fallback_target = secondary or mock
        return FallbackProvider(primary, fallback_target)

    return mock


def _resolve_agent_provider_config(agent_name: str) -> tuple[str, Optional[str], Optional[str], Optional[str]]:
    """Map each agent to its own env vars, keeping the global provider as a fallback."""
    mapping = {
        "ResourceMonitoringAgent": ("MONITORING", "MONITORING_GEMINI_API_KEY", "MONITORING_OPENAI_API_KEY", "MONITORING_LLM_PROVIDER"),
        "RCAAgent": ("RCA", "RCA_GEMINI_API_KEY", "RCA_OPENAI_API_KEY", "RCA_LLM_PROVIDER"),
        "RemediationAgent": ("REMEDIATION", "REMEDIATION_GEMINI_API_KEY", "REMEDIATION_OPENAI_API_KEY", "REMEDIATION_LLM_PROVIDER"),
        "RiskAgent": ("RISK", "RISK_GEMINI_API_KEY", "RISK_OPENAI_API_KEY", "RISK_LLM_PROVIDER"),
        "RiskEngine": ("RISK", "RISK_GEMINI_API_KEY", "RISK_OPENAI_API_KEY", "RISK_LLM_PROVIDER"),
    }
    return mapping.get(agent_name, ("GLOBAL", "GEMINI_API_KEY", "OPENAI_API_KEY", "LLM_PROVIDER"))


def get_llm_provider_for_agent(agent_name: str) -> LLMProvider:
    """Return an LLM provider configured for a specific agent."""
    _, gemini_key_var, openai_key_var, provider_var = _resolve_agent_provider_config(agent_name)
    provider_name = os.getenv(provider_var, os.getenv("LLM_PROVIDER", "auto")).lower()

    gemini_key = os.getenv(gemini_key_var) or os.getenv("GEMINI_API_KEY")
    openai_key = os.getenv(openai_key_var) or os.getenv("OPENAI_API_KEY")

    if provider_name == "mock":
        return _MockProvider()

    if provider_name == "gemini" and gemini_key:
        return GeminiProvider(gemini_key, os.getenv(f"{gemini_key_var.replace('_API_KEY','').replace('GEMINI', '')}_MODEL", os.getenv("GEMINI_MODEL", "gemini-3.5-flash")))

    if provider_name == "openai" and openai_key:
        return OpenAIProvider(openai_key, os.getenv("OPENAI_MODEL", "gpt-4o-mini"))

    if gemini_key:
        return GeminiProvider(gemini_key, os.getenv("GEMINI_MODEL", "gemini-3.5-flash"))

    if openai_key:
        return OpenAIProvider(openai_key, os.getenv("OPENAI_MODEL", "gpt-4o-mini"))

    return _MockProvider()

