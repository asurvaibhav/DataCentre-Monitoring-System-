"""
AO-02 Unified LLM Provider Abstraction.

Supports Google Gemini API and OpenAI API via structured Pydantic outputs.
Falls back to a deterministic mock provider when no API key is configured, so
the pipeline runs end-to-end in sandbox/demo environments without external
credentials. All providers return Pydantic model instances.
"""

from __future__ import annotations

import json
import os
from abc import ABC, abstractmethod
from datetime import datetime, timezone
from typing import Any, Dict, Optional, Type

from pydantic import BaseModel


class LLMProvider(ABC):
    """Abstract provider for structured LLM generation."""

    @abstractmethod
    async def generate_structured(
        self,
        prompt: str,
        schema: Type[BaseModel],
        system_prompt: Optional[str] = None,
        temperature: float = 0.2,
    ) -> BaseModel:
        """Generate a structured Pydantic model instance from a prompt."""
        ...


class _MockProvider(LLMProvider):
    """Deterministic fallback that produces plausible structured outputs
    without calling any external LLM API. Used when no provider key is set."""

    async def generate_structured(
        self,
        prompt: str,
        schema: Type[BaseModel],
        system_prompt: Optional[str] = None,
        temperature: float = 0.2,
    ) -> BaseModel:
        # Build a heuristic instance based on schema name + prompt keywords.
        return _heuristic_instance(schema, prompt)


def _heuristic_instance(schema: Type[BaseModel], prompt: str) -> BaseModel:
    fields = schema.model_fields
    data: Dict[str, Any] = {}

    lower = prompt.lower()

    for field_name, field_info in fields.items():
        fn = field_name.lower()
        field_type = field_info.annotation

        # Handle Optional / Union types by peeking at the inner type.
        origin = getattr(field_type, "__origin__", None)
        args = getattr(field_type, "__args__", None)

        if fn == "root_cause_summary":
            data[field_name] = "Heuristic RCA: sustained utilization growth coupled with " \
                "cross-resource correlation indicates workload-driven saturation."
        elif fn == "attributed_tenant_id":
            data[field_name] = "T1" if "t1" in lower else "T2"
        elif fn == "driving_workload_signature":
            data[field_name] = "Batch analytics workload on tenant DB cluster"
        elif fn == "correlated_signals":
            data[field_name] = ["Rack thermal rise", "Storage IOPS increase"]
        elif fn == "confidence_score":
            data[field_name] = 0.78
        elif fn == "investigation_notes":
            data[field_name] = "Mock investigation notes generated by fallback provider."
        elif fn == "title":
            data[field_name] = "Capacity rebalancing recommendation"
        elif fn == "recommended_action":
            data[field_name] = ("Rebalance affected tenant workloads to under-utilized "
                                "racks to extend lead time.")
        elif fn == "simulated_post_action_utilization_pct":
            data[field_name] = 70.0
        elif fn == "projected_lead_time_extension_weeks":
            data[field_name] = 4.0
        elif fn == "mutates_live_facility_controls":
            data[field_name] = False
        elif fn == "risk_score":
            data[field_name] = 0.55
        elif fn == "blast_radius_summary":
            data[field_name] = "Single rack; limited to one tenant workload."
        elif fn == "sla_impact_assessment":
            data[field_name] = "Moderate; predicted exhaustion within 4-8 weeks."
        elif fn == "gate_decision":
            data[field_name] = "REQUIRE_HUMAN_APPROVAL"
        elif fn == "selected_option_id":
            data[field_name] = "rem-000000"
        elif fn == "option_id":
            import uuid
            data[field_name] = f"rem-{uuid.uuid4().hex[:6]}"
        elif field_type is str:
            data[field_name] = f"mock-{field_name}"
        elif field_type is int:
            data[field_name] = 1
        elif field_type is float:
            data[field_name] = 0.5
        elif field_type is bool:
            data[field_name] = False
        elif field_type is datetime:
            data[field_name] = datetime.now(timezone.utc)
        elif origin is list and args:
            item_type = args[0]
            if item_type is str:
                data[field_name] = []
            else:
                data[field_name] = []
        elif origin is dict:
            data[field_name] = {}
        elif field_type is tuple:
            data[field_name] = (0.0, 0.0)
        else:
            # Use Pydantic default if available.
            if field_info.default is not None:
                data[field_name] = field_info.default
            elif field_info.default_factory is not None:
                data[field_name] = field_info.default_factory()
            else:
                data[field_name] = None

    try:
        return schema(**data)
    except Exception:
        # Last resort: instantiate with defaults only.
        defaults: Dict[str, Any] = {}
        for fname, finfo in fields.items():
            if finfo.default is not None:
                defaults[fname] = finfo.default
            elif finfo.default_factory is not None:
                defaults[fname] = finfo.default_factory()
        return schema(**defaults)


class GeminiProvider(LLMProvider):
    """Google Gemini API provider with structured JSON output."""

    def __init__(self, api_key: str, model_name: str = "gemini-1.5-flash") -> None:
        try:
            import google.generativeai as genai
        except ImportError as exc:  # pragma: no cover - dependency missing
            raise ImportError(
                "google-generativeai is required for the Gemini provider. "
                "Install it with `pip install google-generativeai`."
            ) from exc
        genai.configure(api_key=api_key)
        self._model = genai.GenerativeModel(model_name)

    async def generate_structured(
        self,
        prompt: str,
        schema: Type[BaseModel],
        system_prompt: Optional[str] = None,
        temperature: float = 0.2,
    ) -> BaseModel:
        schema_json = schema.model_json_schema()
        full_prompt = prompt
        if system_prompt:
            full_prompt = f"{system_prompt}\n\n{prompt}"
        full_prompt += (
            "\n\nReturn ONLY a valid JSON object that conforms to this schema:\n"
            f"{json.dumps(schema_json, indent=2)}"
        )

        from google.generativeai import GenerationConfig

        config = GenerationConfig(
            response_mime_type="application/json",
            response_schema=schema_json,
            temperature=temperature,
        )
        response = self._model.generate_content(full_prompt, generation_config=config)
        text = response.text or "{}"
        data = json.loads(text)
        return schema(**data)


class OpenAIProvider(LLMProvider):
    """OpenAI API provider with structured JSON output."""

    def __init__(self, api_key: str, model_name: str = "gpt-4o-mini") -> None:
        try:
            from openai import AsyncOpenAI
        except ImportError as exc:  # pragma: no cover - dependency missing
            raise ImportError(
                "openai is required for the OpenAI provider. "
                "Install it with `pip install openai`."
            ) from exc
        self._client = AsyncOpenAI(api_key=api_key)
        self._model_name = model_name

    async def generate_structured(
        self,
        prompt: str,
        schema: Type[BaseModel],
        system_prompt: Optional[str] = None,
        temperature: float = 0.2,
    ) -> BaseModel:
        schema_json = schema.model_json_schema()
        messages: list[Dict[str, str]] = []
        if system_prompt:
            messages.append({"role": "system", "content": system_prompt})
        messages.append(
            {
                "role": "user",
                "content": (
                    f"{prompt}\n\nReturn ONLY a valid JSON object conforming to "
                    f"this schema: {json.dumps(schema_json)}"
                ),
            }
        )
        response = await self._client.chat.completions.create(
            model=self._model_name,
            messages=messages,
            temperature=temperature,
            response_format={"type": "json_object"},
        )
        text = response.choices[0].message.content or "{}"
        data = json.loads(text)
        return schema(**data)


def get_llm_provider() -> LLMProvider:
    """Factory: return a configured LLM provider or the deterministic mock."""
    provider_name = os.getenv("LLM_PROVIDER", "mock").lower()

    if provider_name == "gemini":
        api_key = os.getenv("GEMINI_API_KEY")
        if api_key:
            return GeminiProvider(api_key)
    elif provider_name == "openai":
        api_key = os.getenv("OPENAI_API_KEY")
        if api_key:
            return OpenAIProvider(api_key)

    # No usable provider key configured — deterministic mock keeps the pipeline runnable.
    return _MockProvider()
